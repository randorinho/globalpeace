ISO2_FROM_ISO3: dict[str, str] = {iso3: iso2 for iso2, iso3, _ in COUNTRIES}
ALL_ISO2: frozenset[str] = frozenset(iso2 for iso2, _, _ in COUNTRIES)

# Longest-alias-first alternation so "South Sudan" beats "Sudan",
# "Guinea-Bissau" beats "Guinea", "Papua New Guinea" beats both.
_ALIAS_TO_ISO2: dict[str, str] = {
    alias: iso2 for iso2, _, aliases in COUNTRIES for alias in aliases
}
_MATCHER = re.compile(
    r"\b(?:" + "|".join(
        re.escape(a) for a in sorted(_ALIAS_TO_ISO2, key=len, reverse=True)
    ) + r")\b",
    re.IGNORECASE,
)


def match_country(text: str) -> str | None:
    """First country named in the text, or None — unmatched items are
    skipped and logged by the caller, never guessed."""
    m = _MATCHER.search(text)
    return _ALIAS_TO_ISO2[m.group(0).lower()] if m else None
